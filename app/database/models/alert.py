"""Alert database model for environmental anomalies and security warnings."""

import enum
import uuid
from datetime import datetime
from typing import Optional, TYPE_CHECKING
from sqlalchemy import String, Float, Enum, ForeignKey, Text, DateTime
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.database.base import Base, TimestampMixin

if TYPE_CHECKING:
    from app.database.models.region import Region
    from app.database.models.tree import Tree
    from app.database.models.environmental_measurement import EnvironmentalMeasurement
    from app.database.models.device import Device


class AlertSeverity(str, enum.Enum):
    """Alert severity levels."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class AlertStatus(str, enum.Enum):
    """Alert lifecycle status."""
    ACTIVE = "ACTIVE"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    RESOLVED = "RESOLVED"
    DISMISSED = "DISMISSED"


class Alert(Base, TimestampMixin):
    """Actionable alert generated by AI anomaly detection or Zero Trust security violations."""
    __tablename__ = "alerts"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    alert_uid: Mapped[str] = mapped_column(
        String(50),
        unique=True,
        index=True,
        default=lambda: str(uuid.uuid4()),
        nullable=False,
    )

    region_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("regions.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # Associated Tree (optional)
    tree_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("trees.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # Associated Measurement (optional)
    measurement_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("environmental_measurements.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # Associated Device (optional)
    device_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("devices.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    alert_type: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    severity: Mapped[AlertSeverity] = mapped_column(
        Enum(AlertSeverity, name="alert_severity"),
        default=AlertSeverity.MEDIUM,
        nullable=False,
        index=True,
    )
    message: Mapped[str] = mapped_column(Text, nullable=False)
    anomaly_score: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    status: Mapped[AlertStatus] = mapped_column(
        Enum(AlertStatus, name="alert_status"),
        default=AlertStatus.ACTIVE,
        nullable=False,
        index=True,
    )

    resolved_by_user_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    resolved_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    resolution_notes: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Relationships
    region: Mapped["Region"] = relationship("Region", back_populates="alerts")
    tree: Mapped[Optional["Tree"]] = relationship("Tree", back_populates="alerts")
    measurement: Mapped[Optional["EnvironmentalMeasurement"]] = relationship(
        "EnvironmentalMeasurement",
        back_populates="alerts",
    )
    device: Mapped[Optional["Device"]] = relationship("Device", back_populates="alerts")

    def __repr__(self) -> str:
        return f"<Alert(id={self.id}, uid='{self.alert_uid}', severity='{self.severity}', status='{self.status}')>"
